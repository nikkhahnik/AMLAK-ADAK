def safe_path(v):
    v = str(v or "")
    return v if v.startswith("/") and not v.startswith("//") else None


def ld(obj):
    obj = dict(obj)
    obj.setdefault("@context", "https://schema.org")
    data = json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return '<script type="application/ld+json">' + data + "</script>"


def breadcrumb(items):
    return {
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": i + 1, "name": name, "item": SITE + path}
            for i, (name, path) in enumerate(items)
        ],
    }


