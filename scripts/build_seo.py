# Tags the managed block owns; stripped from the head before it is inserted.
OWNED = [
    r"<!--seo:start-->.*?<!--seo:end-->",
    r"<title>.*?</title>",
    r'<meta\s+name="(?:description|keywords|robots|twitter:[a-z]+)"[^>]*>',
    r'<meta\s+property="og:[a-z_:]+"[^>]*>',
    r'<link\s+rel="canonical"[^>]*>',
    r'<script type="application/ld\+json">.*?</script>',
]


def apply_head(page, block):
    head_end = page.index("</head>")
    head, rest = page[:head_end], page[head_end:]
    for pat in OWNED:
        head = re.sub(pat, "", head, flags=re.S)
    # keep the site-verification tag (not owned) and put our block after the charset/viewport
    m = re.search(r'<meta name="viewport"[^>]*>', head)
    at = m.end() if m else head.index("<head>") + len("<head>")
    return head[:at] + block + head[at:] + rest


